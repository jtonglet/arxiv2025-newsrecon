def build_articles_and_maps(dataset="tara"):
    articles = []
    processed_articles_dir = "data/processed_articles"
    qwen_class_dir = "data/qwen2.5_article_class"
    caption_paths = ["data/qwen2.5_caption_gt", "data/qwen2.5_caption"]
    for f in sorted(os.listdir(processed_articles_dir)):
        if dataset=='tara':
            #Only remove 2022, 2023, and Guardian part 2 if it is TARA
            if ('2022' in f) or ('2023' in f) or ('guardian_part2' in f) :
                continue
        if f.endswith(".json"):
            articles += load_json(os.path.join(processed_articles_dir, f))
    # qwen2.5 category 1 filter
    qwen_class = []
    for f in sorted(os.listdir(qwen_class_dir)):
        if dataset=='tara':
            if ('2022' in f) or ('2023' in f) or ('guardian_part2' in f):
                continue
        if f.endswith(".json"):
            qwen_class += load_json(os.path.join(qwen_class_dir, f))
    qwen_class = {q['web_url']:q['output'][0]  for q in qwen_class}
    # keep only category 1
    articles = [articles[a] for a in range(len(articles)) if qwen_class[articles[a]['web_url']].lower()=='category 1']
    articles = [a for a in articles if 'glocations' in [kw['name'].lower() for kw in a['keywords']]]
    articles += load_json('data/tara_articles/train.json')
    articles_urls_set = set([a['web_url'] for a in articles])
    #Load news image captions generated by qwen2.5
    captions = []
    for path in caption_paths:
        for file in os.listdir(f"{path}/news_image_caption/"):
            captions += load_json(os.path.join(f"{path}/news_image_caption/",file))

    captions = [c for c in captions if c['web_url'] in articles_urls_set]
    web_urls= [c['web_url'] for c in captions for _ in range(min(len(c['output']), 1))]
    article_caption_indices = {}
    for idx, url in enumerate(web_urls):
        article_caption_indices.setdefault(url, []).append(idx)

    # web_url -> first caption
    url2cap = {}
    for c in captions:
        url = c.get("web_url")
        outs = c.get("output") or []
        if url and outs and outs[0].strip():
            url2cap[url] = outs[0]

    # keep only articles that have a caption
    articles = [a for a in articles if a.get("web_url") in url2cap]

    # build glocations text
    url2loc_text = {}
    for a in articles:
        url = a.get("web_url")
        kws = a.get("keywords", []) or []
        locs = [clean(k.get("value", "")) for k in kws
                if clean(k.get("name", "")).lower() == "glocations" and k.get("value")]
        locs = [x for x in dict.fromkeys(locs) if x]
        if locs:
            url2loc_text[url] = " ; ".join(locs)

    # final set: must have caption and at least one glocation
    valid = sorted(set(url2cap.keys()) & set(url2loc_text.keys()))
    url2cap = {u: url2cap[u] for u in valid}
    url2loc_text = {u: url2loc_text[u] for u in valid}
    url2date = {}
    for a in articles:
        u = a.get("web_url")
        if u in url2cap:
            d = a.get("pub_date")
            if isinstance(d, str) and len(d) >= 10:
                url2date[u] = d[:10]

    return url2cap, url2loc_text, url2date


def load_url2caps(caption_roots, allowed_urls):
    caps = []
    for path in caption_roots.split('-'):
        p = os.path.join(path, "news_image_caption")
        if not os.path.isdir(p):
            continue
        for file in os.listdir(p):
            if file.endswith(".json"):
                caps += load_json(os.path.join(p, file))

    url2caps = {}
    for c in caps:
        url = c.get("web_url")
        if url not in allowed_urls:
            continue
        outs = c.get("output") or []
        texts = [t.strip() for t in outs if isinstance(t, str) and t.strip()]
        if texts:
            url2caps[url] = texts[:1]
    return url2caps


# Cache utilities
def _safe(s):
    return "".join(ch if ch.isalnum() or ch in "._-+" else "_" for ch in s)

def _ckpt_tag(base_ckpt, biencoder_ckpt):
    b = _safe(base_ckpt)
    be = _safe(biencoder_ckpt or "base_model")
    return f"{b}__{be}"

def _hash_list(items):
    h = hashlib.sha1()
    for it in items:
        h.update(it.encode("utf-8"))
        h.update(b"\n")
    return h.hexdigest()[:12]

def _cache_paths(kind, tag, list_hash):
    root = os.path.join(CACHE_DIR, kind, tag)
    os.makedirs(root, exist_ok=True)
    return os.path.join(root, f"{list_hash}.pt"), os.path.join(root, f"{list_hash}.json")

def _save_feats_and_index(tensor, items, kind, tag):
    hh = _hash_list(items)
    pt_path, js_path = _cache_paths(kind, tag, hh)
    torch.save(tensor, pt_path)
    save_json({"items": items}, js_path)
    return pt_path, js_path

def _load_feats_and_index(items, kind, tag):
    hh = _hash_list(items)
    pt_path, js_path = _cache_paths(kind, tag, hh)
    if os.path.isfile(pt_path) and os.path.isfile(js_path):
        meta = load_json(js_path)
        if meta.get("items") == items:
            feats = torch.load(pt_path, map_location="cpu")
            return feats
    return None


def _ce_tag(base_ckpt, cross_head_ckpt):
    b = _safe(base_ckpt)
    h = _safe(cross_head_ckpt or "ce_head")
    return f"{b}__{h}"

def _ce_pair_cache_path(img_path, ce_tag):
    """One JSON file per image, contains { loc_text -> prob } for this CE ckpt tag."""
    img_key = hashlib.sha1(img_path.encode("utf-8")).hexdigest()[:16]
    folder = os.path.join(CACHE_DIR, "ce_pair_scores", ce_tag)
    os.makedirs(folder, exist_ok=True)
    return os.path.join(folder, f"{img_key}.json")


# Encoders (+ caching for frozen/bi)
@torch.no_grad()
def encode_texts_list_cached(clip, texts, processor, tag_prefix, kind = "cap_feats", bs= 256):
    items = list(texts)
    cached = _load_feats_and_index(items, kind, tag_prefix)
    if cached is not None:
        return cached
    feats = []
    for s in tqdm(range(0, len(texts), bs), desc=f"encode {kind}"):
        batch = processor(text=texts[s:s+bs], return_tensors="pt", padding=True, truncation=True).to(device)
        emb = clip.get_text_features(**batch).float().cpu()
        feats.append(emb)
    X = F.normalize(torch.cat(feats, dim=0), dim=-1)
    _save_feats_and_index(X, items, kind, tag_prefix)
    return X


def prepare_multi_caps_index(url2caps):
    """
    Flatten per-URL captions to a single list and build an index tensor to aggregate MAX per article.
    """
    owner_urls = sorted(url2caps.keys())
    flat_caps = []
    idx_lists = []

    for u in owner_urls:
        caps = url2caps[u][:1]
        cur = []
        for cap in caps:
            cur.append(len(flat_caps))
            flat_caps.append(cap)
        idx_lists.append(cur)

    A = len(owner_urls)
    M = max((len(v) for v in idx_lists), default=1)
    idx_mat = torch.full((A, M), -1, dtype=torch.long)
    for a_idx, lst in enumerate(idx_lists):
        for j, flat_idx in enumerate(lst):
            idx_mat[a_idx, j] = flat_idx
    return owner_urls, flat_caps, idx_mat


@torch.no_grad()
def encode_caps_cached(clip, urls, url2cap, processor, base_ckpt, biencoder_ckpt):
    tag = _ckpt_tag(base_ckpt, biencoder_ckpt)
    urls_sorted = list(urls)
    cached = _load_feats_and_index(urls_sorted, "cap_feats", tag)
    if cached is not None:
        return cached, urls_sorted
    feats = []
    bs = 256
    for s in tqdm(range(0, len(urls_sorted), bs), desc="encode captions"):
        texts = [url2cap[u] for u in urls_sorted[s:s+bs]]
        batch = processor(text=texts, return_tensors="pt", padding=True, truncation=True).to(device)
        emb = clip.get_text_features(**batch).float().cpu()
        feats.append(emb)
    feats = F.normalize(torch.cat(feats, dim=0), dim=-1)
    _save_feats_and_index(feats, urls_sorted, "cap_feats", tag)
    return feats, urls_sorted


@torch.no_grad()
def encode_imgs_cached(clip, img_paths, processor, base_ckpt, biencoder_ckpt, split_tag):
    tag = _ckpt_tag(base_ckpt, biencoder_ckpt) + f"__{_safe(split_tag)}"
    cached = _load_feats_and_index(img_paths, "img_feats", tag)
    cached = None
    if cached is not None:
        return cached, img_paths
    feats = []
    bs = 64
    for s in tqdm(range(0, len(img_paths), bs), desc="encode images"):
        paths = img_paths[s:s+bs]
        imgs = [Image.open(p).convert("RGB") for p in paths]
        batch = processor(images=imgs, return_tensors="pt").to(device)
        emb = clip.get_image_features(**batch).float().cpu()
        feats.append(emb)
    feats = F.normalize(torch.cat(feats, dim=0), dim=-1)
    _save_feats_and_index(feats, img_paths, "img_feats", tag)
    return feats, img_paths

