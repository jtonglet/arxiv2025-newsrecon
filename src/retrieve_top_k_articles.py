def _build_time_clusters_from_pool(pool_urls,  url2loc_text, url2date,
                                   Nmin=2, window_days=15,
                                   allowed_tokens = None):
    """
    pool_urls: list[str] top-K urls from BI
    allowed_tokens: if provided, only clusters whose shared token in allowed_tokens are allowed.
    """
    # per-url info
    def _parse(d): return datetime.fromisoformat(d).date()
    info = {}
    for u in pool_urls:
        if u not in url2loc_text or u not in url2date:
            continue
        info[u] = {
            "date": _parse(url2date[u]),
            "tokens": extract_loc_atoms(url2loc_text[u])
        }
    if not info:
        return []

    token2urls = {}
    for u, d in info.items():
        for t in d["tokens"]:
            if allowed_tokens is not None and t not in allowed_tokens:
                continue
            token2urls.setdefault(t, []).append(u)

    clusters, seen = [], set()
    for token, urls in token2urls.items():
        if len(urls) < Nmin:
            continue
        urls_sorted = sorted(urls, key=lambda x: info[x]["date"])
        left = 0
        for right in range(len(urls_sorted)):
            while info[urls_sorted[right]]["date"] - info[urls_sorted[left]]["date"] > timedelta(days=window_days):
                left += 1
            if right - left + 1 >= Nmin:
                group = urls_sorted[left:right+1]
                key = tuple(sorted(group))
                if key in seen:
                    continue
                seen.add(key)
                dmin, dmax = info[group[0]]["date"], info[group[-1]]["date"]

                text = f"An image taken between {dmin.isoformat()} and {dmax.isoformat()} in {token}"
                clusters.append({
                    "urls": group,
                    "token": token,
                    "dmin": dmin.isoformat(),
                    "dmax": dmax.isoformat(),
                    "text": text
                })
    return clusters

