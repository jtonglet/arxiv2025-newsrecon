class CrossEncMLP(nn.Module):
    def __init__(self, 
                 clip_base, 
                 hidden=[256],  
                 operations="concatenation"):
        super().__init__()
        self.clip = clip_base
        self.operations = operations

        # freeze all
        for p in self.clip.parameters():
            p.requires_grad = False

        D = self.clip.config.projection_dim
        # input dim: 2D for "concatenation" (img || txt), +D for each of "multiplication" and "difference"
        in_dim = 0
        if "concatenation" in self.operations:
            in_dim += 2 * D
        if "multiplication" in self.operations:
            in_dim += D
        if "difference" in self.operations:
            in_dim += D

        layers = [nn.Linear(in_dim, hidden[0]), nn.GELU()]
        layers.append(nn.Linear(hidden[0], 1))
        self.head = nn.Sequential(*layers)

    def forward(self, pixel_values, input_ids, attention_mask):
        img_emb = F.normalize(self.clip.get_image_features(pixel_values=pixel_values), dim=-1)
        txt_emb = F.normalize(self.clip.get_text_features(input_ids=input_ids, attention_mask=attention_mask), dim=-1)

        pieces = []
        if "concatenation" in self.operations:
            pieces += [img_emb, txt_emb]
        if "multiplication" in self.operations:
            pieces.append(img_emb * txt_emb)
        if "difference" in self.operations:
            pieces.append((img_emb - txt_emb).abs())

        feat = torch.cat(pieces, dim=-1)
        return self.head(feat).squeeze(1)
    

def _ce_build_features(img_emb, txt_emb, operations):
    """
    Build CE feature vector according to operations:
      - 'concatenation' -> [img, txt]
      - 'multiplication' -> img*txt
      - 'difference' -> |img-txt|
    """
    ops = set(operations.split("-")) if isinstance(operations, str) else set(operations)
    pieces = []
    if "concatenation" in ops:
        pieces += [img_emb, txt_emb]
    if "multiplication" in ops:
        pieces.append(img_emb * txt_emb)
    if "difference" in ops:
        pieces.append((img_emb - txt_emb).abs())
    if not pieces: 
        pieces = [img_emb, txt_emb]
    return torch.cat(pieces, dim=-1)



@torch.no_grad()
def ce_probs_pairs_cached(
    clip_ce, ce_head, processor,
    img_path,
    loc_texts,
    base_ckpt,
    cross_head_ckpt,
    operations = "concatenation",
    bs = 128
):
    tag = _ce_tag(base_ckpt, cross_head_ckpt)
    cache_file = _ce_pair_cache_path(img_path, tag)
    cache = {}
    needed = [t for t in loc_texts if t not in cache]
    if needed:
        img = Image.open(img_path).convert("RGB")
        for s in range(0, len(needed), bs):
            chunk = needed[s:s+bs]
            batch = processor(
                images=[img]*len(chunk),
                text=[f"An image from {t}" for t in chunk],
                return_tensors="pt", padding=True, truncation=True
            ).to(device)
            img_emb = F.normalize(clip_ce.get_image_features(pixel_values=batch["pixel_values"]), dim=-1)
            txt_emb = F.normalize(clip_ce.get_text_features(input_ids=batch["input_ids"], attention_mask=batch["attention_mask"]), dim=-1)
            feat = _ce_build_features(img_emb, txt_emb, operations)
            logits = ce_head(feat).squeeze(1)
            probs = torch.sigmoid(logits).float().cpu().numpy().tolist()
            for t, p in zip(chunk, probs):
                cache[t] = float(p)
        save_json(cache, cache_file)
    return [float(cache[t]) for t in loc_texts]


